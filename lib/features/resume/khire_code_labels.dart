/// 코드의 사용자 언어 표시명. ko=원문(nm), 미등재 코드/언어=en→nm 폴백.
String khireCodeLabel(String? cd, String nm, String lang) {
  if (lang == 'ko' || cd == null) return nm;
  final m = _kKhireCodeLabels[cd];
  if (m == null) return nm;
  return m[lang] ?? m['en'] ?? nm;
}

/// CodeItem 헬퍼.
String khireItemLabel(CodeItem c, String lang) =>
    khireCodeLabel(c.cd, c.nm, lang);

/// 한국어 수준 설명(`title_` + cd) — ko면 원문 title, 그 외 번역.
String khireLevelTitle(CodeItem c, String lang) {
  if (lang == 'ko') return c.title ?? '';
  final m = _kKhireCodeLabels['title_${c.cd}'];
  if (m == null) return c.title ?? '';
  return m[lang] ?? m['en'] ?? (c.title ?? '');
}
